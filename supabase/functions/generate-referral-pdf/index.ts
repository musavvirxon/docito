function formatDateLike(input: unknown, locale: "en" | "ru" | "uz"): string {
  const s = typeof input === "string" ? input : input instanceof Date ? input.toISOString() : "";
  if (!s) return "";
  const d = new Date(s);
  if (Number.isNaN(d.getTime())) return s;
  const yyyy = d.getUTCFullYear();
  const mm = String(d.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(d.getUTCDate()).padStart(2, "0");

  if (locale === "en") return `${yyyy}-${mm}-${dd}`;
  return `${dd}.${mm}.${yyyy}`;
}

function formatDateTimeLike(input: unknown, locale: "en" | "ru" | "uz"): string {
  const s = typeof input === "string" ? input : input instanceof Date ? input.toISOString() : "";
  if (!s) return "";
  const d = new Date(s);
  if (Number.isNaN(d.getTime())) return s;
  const yyyy = d.getUTCFullYear();
  const mm = String(d.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(d.getUTCDate()).padStart(2, "0");
  const hh = String(d.getUTCHours()).padStart(2, "0");
  const mi = String(d.getUTCMinutes()).padStart(2, "0");

  if (locale === "en") return `${yyyy}-${mm}-${dd} ${hh}:${mi} UTC`;
  return `${dd}.${mm}.${yyyy} ${hh}:${mi} UTC`;
}

