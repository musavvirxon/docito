function safeOneLine(v?: unknown, max = 120): string {
  const s = sanitizeString(typeof v === "string" ? v : v == null ? "" : String(v), max);
  return s.replace(/[\r\n]+/g, " ").trim();
}

function wrapText(text: string, font: any, fontSize: number, maxWidth: number): string[] {
  const cleaned = (text || "").replace(/\s+/g, " ").trim();
  if (!cleaned) return [];
  const words = cleaned.split(" ");
  const lines: string[] = [];
  let line = "";

  const pushLine = (l: string) => {
    if (l.trim()) lines.push(l.trim());
  };

  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    const width = font.widthOfTextAtSize(test, fontSize);
    if (width <= maxWidth) {
      line = test;
      continue;
    }

    // If single word too long, break by chars
    if (!line && font.widthOfTextAtSize(w, fontSize) > maxWidth) {
      let chunk = "";
      for (const ch of w) {
        const tt = chunk + ch;
        if (font.widthOfTextAtSize(tt, fontSize) <= maxWidth) {
          chunk = tt;
        } else {
          pushLine(chunk);
          chunk = ch;
        }
      }
      pushLine(chunk);
      line = "";
      continue;
    }

    pushLine(line);
    line = w;
  }

  pushLine(line);
  return lines;
}

function generateVerificationCode(): string {
  const bytes = new Uint8Array(10);
  crypto.getRandomValues(bytes);
  return Array.from(bytes).map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function fetchPatientInfo(service: any, referral: any): Promise<PatientInfo> {
  const patientId = referral.patient_id as string | null;

  // If there is a linked patient id, prefer profiles
  if (patientId) {
    const { data } = await service
      .from("profiles")
      .select("id, user_id, full_name, email, phone, date_of_birth, gender, address")
      .or(`id.eq.${patientId},user_id.eq.${patientId}`)
      .maybeSingle();

    if (data) {
      return {
        name: data.full_name || referral.patient_name || "Unknown",
        phone: data.phone || referral.patient_phone || null,
        email: data.email || referral.patient_email || null,
        dob: data.date_of_birth || referral.patient_dob || null,
        gender: data.gender || referral.patient_gender || null,
        address: data.address || referral.patient_address || null,
      };
    }
  }

  // Fallback to snapshot fields
  return {
    name: referral.patient_name || "Unknown",
    phone: referral.patient_phone || null,
    email: referral.patient_email || null,
    dob: referral.patient_dob || null,
    gender: referral.patient_gender || null,
    address: referral.patient_address || null,
  };
}

