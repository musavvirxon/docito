async function canUserAccessTreatmentPlan(context: any, plan: any): Promise<boolean> {
  const roles: string[] = context?.roles || [];
  const userId: string | null = context?.userId || null;
  const serviceClient: any = context?.serviceClient;

  if (!userId) return false;
  if (roles.includes("super_admin")) return true;

  const patientId = asString(plan?.patient_id);
  if (patientId && patientId === userId) return true;

  const doctorId = asString(plan?.doctor_id) || asString(plan?.dentist_id);
  if (!doctorId) return false;

  try {
    const { data } = await serviceClient
      .from("doctors")
      .select("id,user_id")
      .eq("id", doctorId)
      .maybeSingle();
    const doctorUserId = asString((data as any)?.user_id);
    return !!doctorUserId && doctorUserId === userId;
  } catch {
    return false;
  }
}

