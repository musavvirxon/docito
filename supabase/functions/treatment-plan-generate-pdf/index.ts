function mapUniversalToFdi(n: number): number | null {
  // Universal 1..32 -> FDI 11..48
  if (n < 1 || n > 32) return null;
  const map: Record<number, number> = {
    1: 18, 2: 17, 3: 16, 4: 15, 5: 14, 6: 13, 7: 12, 8: 11,
    9: 21, 10: 22, 11: 23, 12: 24, 13: 25, 14: 26, 15: 27, 16: 28,
    17: 38, 18: 37, 19: 36, 20: 35, 21: 34, 22: 33, 23: 32, 24: 31,
    25: 41, 26: 42, 27: 43, 28: 44, 29: 45, 30: 46, 31: 47, 32: 48,
  };
  return map[n] ?? null;
}

function normalizeToothNumberToFdi(n: number): number | null {
  // If already looks like FDI permanent range
  if (n >= 11 && n <= 48) return n;
  // Universal system
  if (n >= 1 && n <= 32) return mapUniversalToFdi(n);
  return null;
}

function drawDentalChart(params: {
  page: PDFPage;
  font: PDFFont;
  locale: Locale;
  x: number;
  yTop: number;
  width: number;
  height: number;
  highlightedFdi: Set<number>;
}) {
  const { page, font, locale, x, yTop, width, height, highlightedFdi } = params;

  const border = rgb(0.9, 0.9, 0.9);
  const labelColor = rgb(0.25, 0.25, 0.25);
  const textColor = rgb(0.05, 0.05, 0.05);
  const fillNormal = rgb(0.98, 0.98, 0.98);
  const fillHighlight = rgb(0.90, 0.95, 1.00);

  // Chart box
  page.drawRectangle({
    x,
    y: yTop - height,
    width,
    height,
    borderColor: border,
    borderWidth: 1,
    color: rgb(1, 1, 1),
  });

  const padding = 10;
  const innerX = x + padding;
  const innerW = width - padding * 2;

  const rowGap = 10;
  const rowH = (height - padding * 2 - rowGap) / 2;

  const cols = 16;
  const gap = 2;
  const boxW = (innerW - gap * (cols - 1)) / cols;
  const boxH = rowH;

  const upper: number[] = [18, 17, 16, 15, 14, 13, 12, 11, 21, 22, 23, 24, 25, 26, 27, 28];
  const lower: number[] = [48, 47, 46, 45, 44, 43, 42, 41, 31, 32, 33, 34, 35, 36, 37, 38];

  const drawRow = (row: number[], yRowTop: number) => {
    const yBox = yRowTop - boxH;

    for (let i = 0; i < cols; i++) {
      const tn = row[i];
      const isHL = highlightedFdi.has(tn);
      const bx = innerX + i * (boxW + gap);

      page.drawRectangle({
        x: bx,
        y: yBox,
        width: boxW,
        height: boxH,
        borderColor: border,
        borderWidth: 1,
        color: isHL ? fillHighlight : fillNormal,
      });

      const label = String(tn);
      const fs = 8;
      const tw = font.widthOfTextAtSize(label, fs);
      page.drawText(label, {
        x: bx + (boxW - tw) / 2,
        y: yBox + boxH / 2 - 4,
        size: fs,
        font,
        color: textColor,
      });
    }
  };

  const upperTop = yTop - padding;
  const lowerTop = yTop - padding - rowH - rowGap;

  drawRow(upper, upperTop);
  drawRow(lower, lowerTop);

  // Small legend (translated)
  const legend = `${t(locale, "teethInvolved")}: ${Array.from(highlightedFdi).sort((a, b) => a - b).join(", ") || t(locale, "na")}`;
  const rtl = isRtlLocale(locale);
  const legendText = formatForLocale(locale, legend);
  const legendY = yTop - height + 6;

  const legendSize = 9;
  const legendW = innerW;
  if (rtl) {
    const w = font.widthOfTextAtSize(legendText, legendSize);
    page.drawText(legendText, {
      x: innerX + legendW - w,
      y: legendY,
      size: legendSize,
      font,
      color: labelColor,
    });
  } else {
    page.drawText(legendText, {
      x: innerX,
      y: legendY,
      size: legendSize,
      font,
      color: labelColor,
    });
  }
}

