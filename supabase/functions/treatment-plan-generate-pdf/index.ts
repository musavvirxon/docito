function reverseRange(chars: string[], start: number, end: number) {
  let i = start;
  let j = end;
  while (i < j) {
    const tmp = chars[i];
    chars[i] = chars[j];
    chars[j] = tmp;
    i++;
    j--;
  }
}

function shapeArabicDisplay(text: string): string {
  try {
    const arabicShaper = (reshaper as any)?.ArabicShaper;
    const shaped = typeof arabicShaper?.convertArabic === "function"
      ? arabicShaper.convertArabic(text)
      : text;

    const bidi = (bidiFactory as any)();
    const embedding = bidi.getEmbeddingLevels(shaped, "rtl");
    const flips: Array<[number, number]> = bidi.getReorderSegments(shaped, embedding);

    const chars = shaped.split("");
    for (const [s, e] of flips) reverseRange(chars, s, e);
    return chars.join("");
  } catch {
    return text;
  }
}

function formatForLocale(locale: Locale, text: string): string {
  if (locale === "ar") return shapeArabicDisplay(text);
  return text;
}

function wrapText(font: PDFFont, text: string, fontSize: number, maxWidth: number): string[] {
  const clean = (text || "").replace(/\s+/g, " ").trim();
  if (!clean) return [];

  // Prefer space-based wrapping, but handle CJK / long tokens
  const hasSpaces = /\s/.test(clean);
  const tokens = hasSpaces ? clean.split(" ") : Array.from(clean); // grapheme-ish via codepoints

  const lines: string[] = [];
  let current = "";

  for (const token of tokens) {
    const candidate = current ? (hasSpaces ? `${current} ${token}` : `${current}${token}`) : token;
    const w = font.widthOfTextAtSize(candidate, fontSize);

    if (w <= maxWidth) {
      current = candidate;
      continue;
    }

    if (current) lines.push(current);
    current = token;

    // If a single token is wider than maxWidth (very long word), split by characters
    if (font.widthOfTextAtSize(current, fontSize) > maxWidth) {
      const chars = Array.from(current);
      let sub = "";
      for (const ch of chars) {
        const c2 = sub ? `${sub}${ch}` : ch;
        if (font.widthOfTextAtSize(c2, fontSize) <= maxWidth) {
          sub = c2;
        } else {
          if (sub) lines.push(sub);
          sub = ch;
        }
      }
      current = sub;
    }
  }

  if (current) lines.push(current);
  return lines;
}

type DrawTextOpts = {
  page: PDFPage;
  font: PDFFont;
  x: number;
  y: number;
  size: number;
  maxWidth: number;
  color?: { r: number; g: number; b: number };
  rtl?: boolean;
};

function drawWrappedText(text: string, opts: DrawTextOpts): { lines: number; yAfter: number } {
  const { page, font, x, y, size, maxWidth, color, rtl } = opts;
  const lines = wrapText(font, text, size, maxWidth);
  let yy = y;
  const gap = 14;

  for (const rawLine of lines.length ? lines : [""]) {
    const line = rawLine || "";
    if (rtl) {
      const w = font.widthOfTextAtSize(line, size);
      page.drawText(line, { x: x + maxWidth - w, y: yy, size, font, color: color ? rgb(color.r, color.g, color.b) : rgb(0.05, 0.05, 0.05) });
    } else {
      page.drawText(line, { x, y: yy, size, font, color: color ? rgb(color.r, color.g, color.b) : rgb(0.05, 0.05, 0.05) });
    }
    yy -= gap;
  }

  return { lines: lines.length || 1, yAfter: yy };
}

