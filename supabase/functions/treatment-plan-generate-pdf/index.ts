function t(locale: Locale, key: string): string {
  return I18N[locale]?.[key] || I18N.en[key] || key;
}

function safeText(v: unknown, fallback: string): string {
  const s = typeof v === "string" ? v.trim() : "";
  return s.length ? s : fallback;
}

function safeArray(v: unknown): any[] {
  return Array.isArray(v) ? v : [];
}

function isoDateTime(v: unknown): string | null {
  const s = typeof v === "string" ? v.trim() : "";
  if (!s) return null;
  const d = new Date(s);
  if (isNaN(d.getTime())) return null;
  return d.toISOString().replace("T", " ").slice(0, 19) + "Z";
}

function money(v: unknown): string | null {
  if (typeof v === "number" && isFinite(v)) return v.toFixed(2);
  if (typeof v === "string") {
    const s = v.trim();
    if (!s) return null;
    const n = Number(s);
    if (isFinite(n)) return n.toFixed(2);
    return s;
  }
  return null;
}

function sanitizeFileName(name: string): string {
  return name.replace(/[^\w.\-]+/g, "_").slice(0, 120);
}

function wrapText(font: any, text: string, size: number, maxWidth: number): string[] {
  const clean = (text || "").replace(/\s+/g, " ").trim();
  if (!clean) return [];
  const words = clean.split(" ");
  const lines: string[] = [];
  let line = "";

  for (const w of words) {
    const cand = line ? `${line} ${w}` : w;
    const width = font.widthOfTextAtSize(cand, size);
    if (width > maxWidth) {
      if (line) lines.push(line);
      line = w;
    } else {
      line = cand;
    }
  }

  if (line) lines.push(line);
  return lines;
}

async function getUserPreferredLocale(serviceClient: any, userId: string): Promise<Locale> {
  // 1) user_preferences.preferred_language
  try {
    const { data, error } = await serviceClient
      .from("user_preferences")
      .select("preferred_language")
      .eq("user_id", userId)
      .maybeSingle();
    if (!error) {
      const lang = (data as any)?.preferred_language;
      if (typeof lang === "string" && lang.trim()) return normalizeLocale(lang);
    }
  } catch {
    // ignore
  }

  // 2) profiles.language (some deployments had this column)
  try {
    const { data, error } = await serviceClient
      .from("profiles")
      .select("language")
      .eq("user_id", userId)
      .maybeSingle();
    if (!error) {
      const lang = (data as any)?.language;
      if (typeof lang === "string" && lang.trim()) return normalizeLocale(lang);
    }
  } catch {
    // ignore
  }

  return "en";
}

async function getDoctorDisplay(serviceClient: any, doctorId: string, locale: Locale): Promise<{ name: string | null; specialty: string | null }>{
  const { data } = await serviceClient
    .from("doctors")
    .select("id, user_id, specialty, specialty_en, specialty_ru, specialty_uz")
    .eq("id", doctorId)
    .maybeSingle();

  const d = data as any;
  const userId = d?.user_id ? String(d.user_id) : null;

  let fullName: string | null = null;
  if (userId) {
    const { data: p } = await serviceClient
      .from("profiles")
      .select("full_name")
      .eq("user_id", userId)
      .maybeSingle();
    fullName = (p as any)?.full_name ? String((p as any).full_name) : null;
  }

  const specKey = locale === "ru" ? "specialty_ru" : locale === "uz" ? "specialty_uz" : "specialty_en";
  const specialty = (d as any)?.[specKey] ? String((d as any)[specKey]) : (d?.specialty ? String(d.specialty) : null);

  return { name: fullName, specialty };
}

async function fetchPlanWithAccess(context: any, planId: string): Promise<{ plan: any; doctorId: string | null } | null> {
  const { data: plan, error } = await context.serviceClient
    .from("treatment_plans")
    .select("*")
    .eq("id", planId)
    .maybeSingle();

  if (error) throw error;
  if (!plan) return null;

  const roles: string[] = context.roles || [];
  const userId: string | null = context.userId || null;
  if (!userId) return null;

  const rawDoctorId = (plan as any)?.doctor_id || (plan as any)?.dentist_id || null;
  const doctorId = rawDoctorId ? String(rawDoctorId) : null;

  // Super admin always allowed
  if (roles.includes("super_admin")) return { plan, doctorId };

  // Patient allowed if matches
  const patientId = (plan as any)?.patient_id ? String((plan as any).patient_id) : null;
  if (patientId && patientId === userId) return { plan, doctorId };

  // Doctor allowed if owns this plan (match doctors.id by user_id)
  const { data: d } = await context.serviceClient
    .from("doctors")
    .select("id")
    .eq("user_id", userId)
    .maybeSingle();

  const myDoctorId = (d as any)?.id ? String((d as any).id) : null;
  if (myDoctorId && doctorId && myDoctorId === doctorId) return { plan, doctorId };

  return null;
}

async function listPlanProcedures(serviceClient: any, planId: string): Promise<any[]> {
  // Order may drift; try sequence_order first, then created_at.
  const base = serviceClient.from("treatment_plan_procedures").select("*").eq("treatment_plan_id", planId);

  try {
    const r1 = await base.order("sequence_order", { ascending: true });
    if (!r1.error) return (r1.data || []) as any[];
  } catch {
    // ignore
  }

  const r2 = await base.order("created_at", { ascending: true });
  if (r2.error) throw r2.error;
  return (r2.data || []) as any[];
}

