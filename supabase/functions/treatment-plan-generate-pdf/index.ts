async function buildPdf(params: {
  locale: Locale;
  plan: any;
  patientProfile: any | null;
  doctorDisplay: { name: string | null; specialty: string | null } | null;
  procedures: any[];
  medications: any[];
  consents: any[];
  attachments: any[];
}) {
  const W = 595.28; // A4
  const H = 841.89;
  const margin = 44;

  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);

  const fontBytes = b64ToBytes(DOCITO_FONT_TTF_BASE64);
  const font = await pdf.embedFont(fontBytes, { subset: true });

  const logoBytes = b64ToBytes(DOCITO_LOGO_PNG_BASE64);
  const logo = await pdf.embedPng(logoBytes);

  const logoW = 42;
  const logoH = (logo.height / logo.width) * logoW;

  const planId = String(params.plan?.id || "");
  const verificationCode = safeText(params.plan?.verification_code, planId || t(params.locale, "na"));
  const verifyUrl = `https://docito.app/verify/treatment-plan?code=${encodeURIComponent(verificationCode)}`;

  let pageIndex = 0;
  let page = pdf.addPage([W, H]);
  let y = H - margin;

  const header = (continued = false) => {
    y = H - margin;

    page.drawImage(logo, { x: margin, y: y - logoH, width: logoW, height: logoH });

    page.drawText("docito.app", {
      x: W - margin - font.widthOfTextAtSize("docito.app", 10),
      y: y - 12,
      size: 10,
      font,
      color: rgb(0.25, 0.25, 0.25),
    });

    y -= logoH + 18;

    const title = continued ? `${t(params.locale, "title")} (${pageIndex + 1})` : t(params.locale, "title");
    page.drawText(title, {
      x: margin,
      y,
      size: 20,
      font,
      color: rgb(0.05, 0.05, 0.05),
    });

    y -= 18;

    page.drawLine({
      start: { x: margin, y },
      end: { x: W - margin, y },
      thickness: 1,
      color: rgb(0.85, 0.85, 0.85),
    });

    y -= 16;
  };

  const newPage = () => {
    pageIndex += 1;
    page = pdf.addPage([W, H]);
    header(true);
  };

  const ensureSpace = (needed: number) => {
    if (y - needed < margin + 90) newPage();
  };

  const colLabelX = margin;
  const colValueX = margin + 170;
  const maxValueW = W - margin - colValueX;
  const labelSize = 10;
  const valueSize = 10;
  const lineGap = 14;

  const drawKV = (label: string, value: string) => {
    const lines = wrapText(font, value, valueSize, maxValueW);
    const needed = Math.max(1, lines.length || 1) * lineGap + 2;
    ensureSpace(needed);

    page.drawText(label, { x: colLabelX, y, size: labelSize, font, color: rgb(0.25, 0.25, 0.25) });

    if (lines.length === 0) {
      page.drawText(t(params.locale, "na"), { x: colValueX, y, size: valueSize, font, color: rgb(0.05, 0.05, 0.05) });
      y -= lineGap;
      return;
    }

    for (let i = 0; i < lines.length; i++) {
      page.drawText(lines[i], { x: colValueX, y, size: valueSize, font, color: rgb(0.05, 0.05, 0.05) });
      y -= lineGap;
    }
  };

  const drawSection = (title: string) => {
    ensureSpace(40);
    y -= 6;
    page.drawText(title, { x: margin, y, size: 12, font, color: rgb(0.1, 0.1, 0.1) });
    y -= 10;
    page.drawLine({
      start: { x: margin, y },
      end: { x: W - margin, y },
      thickness: 0.8,
      color: rgb(0.9, 0.9, 0.9),
    });
    y -= 14;
  };

  const drawListItem = (text: string) => {
    const x = margin + 10;
    const maxW = W - margin - x;
    const lines = wrapText(font, text, 10, maxW);
    const needed = Math.max(1, lines.length) * 14 + 2;
    ensureSpace(needed);

    page.drawText("•", { x: margin, y, size: 11, font, color: rgb(0.25, 0.25, 0.25) });
    for (const ln of lines) {
      page.drawText(ln, { x, y, size: 10, font, color: rgb(0.05, 0.05, 0.05) });
      y -= 14;
    }
  };

  const drawProcedureTable = (rows: any[]) => {
    ensureSpace(60);

    const tableX = margin;
    const tableW = W - margin * 2;

    const c1 = 26;  // #
    const c2 = 260; // procedure
    const c3 = 70;  // tooth
    const c4 = 90;  // status
    const c5 = tableW - (c1 + c2 + c3 + c4); // cost

    const headerY = y;
    const rowH = 18;

    const drawHeaderCell = (text: string, x: number, w: number) => {
      page.drawText(text, { x: x + 4, y: headerY, size: 10, font, color: rgb(0.25, 0.25, 0.25) });
      page.drawLine({ start: { x, y: headerY - 6 }, end: { x: x + w, y: headerY - 6 }, thickness: 0.6, color: rgb(0.9, 0.9, 0.9) });
    };

    drawHeaderCell(t(params.locale, "colN"), tableX, c1);
    drawHeaderCell(t(params.locale, "colProcedure"), tableX + c1, c2);
    drawHeaderCell(t(params.locale, "colTooth"), tableX + c1 + c2, c3);
    drawHeaderCell(t(params.locale, "colStatus"), tableX + c1 + c2 + c3, c4);
    drawHeaderCell(t(params.locale, "colCost"), tableX + c1 + c2 + c3 + c4, c5);

    y -= 18;

    for (let i = 0; i < rows.length; i++) {
      const r = rows[i] || {};
      const idx = String(i + 1);

      const procName = safeText(
        r.display_name,
        safeText(r.procedure_name, safeText(r.name, t(params.locale, "na"))),
      );

      const tooth = Array.isArray(r.tooth_numbers) && r.tooth_numbers.length
        ? r.tooth_numbers.join(",")
        : safeText(r.tooth, t(params.locale, "na"));

      const status = safeText(r.status, t(params.locale, "na"));
      const costStr = safeText(r.cost, t(params.locale, "na"));

      const procLines = wrapText(font, procName, 10, c2 - 8);
      const linesCount = Math.max(1, procLines.length);
      const needed = linesCount * 14 + 10;
      ensureSpace(needed);

      // #
      page.drawText(idx, { x: tableX + 4, y, size: 10, font, color: rgb(0.05, 0.05, 0.05) });

      // Procedure (wrapped)
      let yy = y;
      for (const ln of procLines.length ? procLines : [t(params.locale, "na")]) {
        page.drawText(ln, { x: tableX + c1 + 4, y: yy, size: 10, font, color: rgb(0.05, 0.05, 0.05) });
        yy -= 14;
      }

      // Tooth / Status / Cost align to first line
      page.drawText(tooth, { x: tableX + c1 + c2 + 4, y, size: 10, font, color: rgb(0.05, 0.05, 0.05) });
      page.drawText(status, { x: tableX + c1 + c2 + c3 + 4, y, size: 10, font, color: rgb(0.05, 0.05, 0.05) });

      const costX = tableX + c1 + c2 + c3 + c4 + 4;
      page.drawText(costStr, { x: costX, y, size: 10, font, color: rgb(0.05, 0.05, 0.05) });

      // Row separator
      const sepY = y - (linesCount * 14) - 2;
      page.drawLine({
        start: { x: tableX, y: sepY },
        end: { x: tableX + tableW, y: sepY },
        thickness: 0.5,
        color: rgb(0.93, 0.93, 0.93),
      });

      y = sepY - 10;
    }
  };

  header(false);

  // ---- Plan details ----
  drawSection(t(params.locale, "title"));

  const status = safeText(params.plan?.status, t(params.locale, "na"));
  const createdAt = isoDateTime(params.plan?.created_at) || t(params.locale, "na");
  const updatedAt = isoDateTime(params.plan?.updated_at) || t(params.locale, "na");
  const publishedAt = isoDateTime(params.plan?.published_at) || t(params.locale, "na");
  const completedAt = isoDateTime(params.plan?.completed_at) || t(params.locale, "na");

  const title = safeText(params.plan?.title, t(params.locale, "na"));
  const description = safeText(params.plan?.description, "");
  const notes = safeText(params.plan?.notes, "");

  const totalCost = money(params.plan?.total_cost) || money(params.plan?.totalCost) || t(params.locale, "na");

  drawKV(t(params.locale, "planId"), safeText(planId, t(params.locale, "na")));
  drawKV(t(params.locale, "verificationCode"), safeText(verificationCode, t(params.locale, "na")));
  drawKV(t(params.locale, "status"), status);
  drawKV(t(params.locale, "createdAt"), createdAt);
  drawKV(t(params.locale, "updatedAt"), updatedAt);

  if (safeText(params.plan?.published_at, "").length) drawKV(t(params.locale, "publishedAt"), publishedAt);
  if (safeText(params.plan?.completed_at, "").length) drawKV(t(params.locale, "completedAt"), completedAt);

  drawKV(t(params.locale, "totalCost"), totalCost);
  drawKV(t(params.locale, "name"), title);

  if (description) drawKV(t(params.locale, "description"), description);
  if (notes) drawKV(t(params.locale, "notes"), notes);

  // ---- Patient ----
  drawSection(t(params.locale, "patient"));

  const p = params.patientProfile || null;
  drawKV(t(params.locale, "name"), safeText(p?.full_name, t(params.locale, "na")));
  drawKV(t(params.locale, "phone"), safeText(p?.phone, t(params.locale, "na")));
  drawKV(t(params.locale, "email"), safeText(p?.email, t(params.locale, "na")));
  drawKV(t(params.locale, "dob"), safeText(p?.date_of_birth, t(params.locale, "na")));
  drawKV(t(params.locale, "gender"), safeText(p?.gender, t(params.locale, "na")));
  drawKV(t(params.locale, "address"), safeText(p?.address, t(params.locale, "na")));

  // ---- Doctor ----
  drawSection(t(params.locale, "doctor"));
  drawKV(t(params.locale, "name"), safeText(params.doctorDisplay?.name, t(params.locale, "na")));
  drawKV(t(params.locale, "specialty"), safeText(params.doctorDisplay?.specialty, t(params.locale, "na")));

  // ---- Procedures ----
  drawSection(t(params.locale, "procedures"));
  if (params.procedures.length === 0) {
    drawKV(t(params.locale, "procedures"), t(params.locale, "na"));
  } else {
    drawProcedureTable(params.procedures);
  }

  // ---- Medications ----
  drawSection(t(params.locale, "medications"));
  if (params.medications.length === 0) {
    drawKV(t(params.locale, "medications"), t(params.locale, "na"));
  } else {
    for (const m of params.medications) {
      const name = safeText(m?.medication_name, safeText(m?.name, t(params.locale, "na")));
      const dosage = safeText(m?.dosage, "");
      const frequency = safeText(m?.frequency, "");
      const start = safeText(m?.start_date, "");
      const end = safeText(m?.end_date, "");
      const instr = safeText(m?.instructions, "");

      const parts = [
        name,
        dosage ? `• ${dosage}` : "",
        frequency ? `• ${frequency}` : "",
        start || end ? `• ${[start, end].filter(Boolean).join(" → ")}` : "",
        instr ? `• ${instr}` : "",
      ].filter(Boolean);

      drawListItem(parts.join(" "));
    }
  }

  // ---- Consent forms ----
  drawSection(t(params.locale, "consentForms"));
  if (params.consents.length === 0) {
    drawKV(t(params.locale, "consentForms"), t(params.locale, "na"));
  } else {
    for (const c of params.consents) {
      const titleC = safeText(c?.title, t(params.locale, "na"));
      const statusC = safeText(c?.status, t(params.locale, "na"));
      const signedAt = isoDateTime(c?.signed_at) || "";
      const line = `${titleC} • ${statusC}${signedAt ? ` • ${signedAt}` : ""}`;
      drawListItem(line);
    }
  }

  // ---- Attachments ----
  drawSection(t(params.locale, "attachments"));
  if (params.attachments.length === 0) {
    drawKV(t(params.locale, "attachments"), t(params.locale, "na"));
  } else {
    for (const a of params.attachments) {
      const file = safeText(a?.file_name, safeText(a?.name, t(params.locale, "na")));
      const type = safeText(a?.file_type, "");
      const size = typeof a?.file_size === "number" ? `${a.file_size} B` : safeText(a?.file_size, "");
      const line = [file, type ? `• ${type}` : "", size ? `• ${size}` : ""].filter(Boolean).join(" ");
      drawListItem(line);
    }
  }

  // ---- Footer verification (last page) ----
  ensureSpace(110);
  const footerY = margin + 30;

  page.drawLine({
    start: { x: margin, y: footerY + 70 },
    end: { x: W - margin, y: footerY + 70 },
    thickness: 0.8,
    color: rgb(0.9, 0.9, 0.9),
  });

  page.drawText(t(params.locale, "generatedBy"), {
    x: margin,
    y: footerY + 8,
    size: 9,
    font,
    color: rgb(0.35, 0.35, 0.35),
  });

  page.drawText(t(params.locale, "verification") + ":", {
    x: margin,
    y: footerY + 44,
    size: 10,
    font,
    color: rgb(0.25, 0.25, 0.25),
  });

  page.drawText(`${t(params.locale, "verificationCode")}: ${verificationCode}`, {
    x: margin,
    y: footerY + 30,
    size: 9,
    font,
    color: rgb(0.05, 0.05, 0.05),
  });

  page.drawText(`${t(params.locale, "verifyAt")}: ${verifyUrl}`, {
    x: margin,
    y: footerY + 18,
    size: 9,
    font,
    color: rgb(0.05, 0.05, 0.05),
  });

  try {
    const dataUrl = await QRCode.toDataURL(verifyUrl, { margin: 1, width: 140 });
    const b64 = dataUrl.split(",")[1] || "";
    if (b64) {
      const qrBytes = b64ToBytes(b64);
      const qr = await pdf.embedPng(qrBytes);
      const qrW = 92;
      const qrH = 92;
      page.drawImage(qr, { x: W - margin - qrW, y: footerY + 6, width: qrW, height: qrH });
    }
  } catch {
    // ignore QR failures
  }

  return await pdf.save();
}

serve(async (req) => {
  const sec = await secureHandler(req, "treatment-plan-generate-pdf", {
    requireAuth: true,
    allowedMethods: ["POST", "OPTIONS"],
    rateLimit: "standard",
    validationSchema: schema,
  });

  if (sec.response) return sec.response;

  const context = sec.context!;
  const body = sec.validatedBody as ReqBody;

  try {
    const planId = body.treatment_plan_id;
    const locale = body.locale
      ? normalizeLocale(body.locale)
      : await getUserPreferredLocale(context.serviceClient, context.userId!);

    const access = await fetchPlanWithAccess(context, planId);
    if (!access) return errorResponse("Insufficient permissions", 403);

    const plan = access.plan;
    const patientId = plan?.patient_id ? String(plan.patient_id) : null;

    let patientProfile: any | null = null;
    if (patientId) {
      const { data } = await context.serviceClient
        .from("profiles")
        .select("*")
        .eq("user_id", patientId)
        .maybeSingle();
      patientProfile = (data as any) || null;
    }

    let doctorDisplay: { name: string | null; specialty: string | null } | null = null;
    if (access.doctorId) {
      doctorDisplay = await getDoctorDisplay(context.serviceClient, access.doctorId, locale);
    }

    const rawProcedures = await listPlanProcedures(context.serviceClient, planId);

    // If treatment_plan_procedures has procedure_id, map to procedures table for names/default cost if needed
    const procedureIds = Array.from(
      new Set(
        rawProcedures
          .map((p: any) => p?.procedure_id)
          .filter((x: any) => typeof x === "string" && x.length > 10),
      ),
    ) as string[];

    const catalogById = new Map<string, any>();
    if (procedureIds.length > 0) {
      try {
        const { data } = await context.serviceClient
          .from("procedures")
          .select("*")
          .in("id", procedureIds);
        for (const r of safeArray(data)) {
          if (r?.id) catalogById.set(String(r.id), r);
        }
      } catch {
        // ignore
      }
    }

    const procedures = rawProcedures.map((p: any) => {
      const pid = p?.procedure_id ? String(p.procedure_id) : null;
      const cat = pid ? catalogById.get(pid) : null;

      const displayName =
        safeText(p?.procedure_name, "") ||
        safeText(cat?.name, "") ||
        safeText(p?.name, "") ||
        safeText(cat?.procedure_name, "") ||
        "";

      const tooth_numbers = Array.isArray(p?.tooth_numbers) ? p.tooth_numbers : null;

      const costVal =
        money(p?.custom_cost) ||
        money(p?.cost) ||
        money(p?.custom_price) ||
        money(cat?.default_cost) ||
        money(cat?.default_price) ||
        null;

      return {
        ...p,
        display_name: displayName,
        tooth_numbers,
        cost: costVal || t(locale, "na"),
      };
    });

    const medications = await listPlanMedications(context.serviceClient, planId);
    const consents = await listPlanConsents(context.serviceClient, planId);
    const attachments = await listPlanAttachments(context.serviceClient, planId);

    const pdfBytes = await buildPdf({
      locale,
      plan,
      patientProfile,
      doctorDisplay,
      procedures,
      medications,
      consents,
      attachments,
    });

    const verificationCode = safeText(plan?.verification_code, safeText(plan?.id, "treatment_plan"));
    const fileName = sanitizeFileName(`treatment-plan_${verificationCode}.pdf`);

    return new Response(pdfBytes, {
      status: 200,
      headers: {
        ...corsHeaders,
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="${fileName}"`,
      },
    });
  } catch (e) {
    console.error("treatment-plan-generate-pdf error:", e);
    return errorResponse("Failed to generate PDF", 500);
  }
});
